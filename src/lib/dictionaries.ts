import Dexie, { type Table } from "dexie";

export interface WordDefinition {
  word: string;
  phonetic?: string;
  partOfSpeech: string;
  definition: string;
  example?: string;
  synonyms?: string[];
  category?: string;
}

export interface DictionaryItem {
  id: string;
  name: string;
  description: string;
  category: string;
  cardCount: number;
  author: string;
  downloads: number;
  rating: number;
  tags: string[];
  cards: {
    front: string;
    back: string;
    tags?: string[];
  }[];
}

export interface LocalDownloadedDictionary {
  id: string;
  dictionaryId: string;
  name: string;
  description: string;
  cardCount: number;
  downloadedAt: string;
  deckId?: string;
}

export class DictionariesDatabase extends Dexie {
  downloadedDictionaries!: Table<LocalDownloadedDictionary>;
  cachedWords!: Table<WordDefinition & { id?: number }>;

  constructor() {
    super("english-flashcards-dictionaries");
    this.version(2).stores({
      downloadedDictionaries: "id, dictionaryId, name, downloadedAt",
      cachedWords: "++id, word, category",
    });
  }
}

